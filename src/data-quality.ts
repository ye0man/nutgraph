/**
 * Data-quality ledger.
 *
 * Every stage can record an issue here instead of silently dropping or guessing
 * at bad data. `nutgraph build` renders this to DATA_QUALITY.md and reports the
 * count in the agent manifest, so problems are visible and fixable rather than
 * buried in logs.
 */

export type Severity = "error" | "warn" | "info";

export interface DqIssue {
  code: string;
  severity: Severity;
  subject: string;
  detail: string;
  suggestion?: string;
}

