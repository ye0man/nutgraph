export class DataQualityLog {
  private issues: DqIssue[] = [];

  add(issue: DqIssue): void {
    this.issues.push(issue);
  }

  get all(): readonly DqIssue[] {
    return this.issues;
  }

  get count(): number {
    return this.issues.length;
  }

  bySeverity(): Record<Severity, number> {
    return this.issues.reduce(
      (acc, i) => ((acc[i.severity] = (acc[i.severity] ?? 0) + 1), acc),
      { error: 0, warn: 0, info: 0 } as Record<Severity, number>,
    );
  }

  renderMarkdown(generatedAt: string): string {
    const counts = this.bySeverity();
    const lines: string[] = [];
    lines.push("# Data quality ledger");
    lines.push("");
    lines.push(
      "Auto-generated by `nutgraph build`. Do not edit by hand -- fix the underlying",
    );
    lines.push("data or add an override, then rebuild.");
    lines.push("");
    lines.push(`Generated: ${generatedAt}`);
    lines.push("");
    lines.push(
      `**${this.issues.length} issue(s)** -- ${counts.error} error, ${counts.warn} warn, ${counts.info} info.`,
    );
    lines.push("");

    const codes = [...new Set(this.issues.map((i) => i.code))].sort();
    for (const code of codes) {
      const group = this.issues.filter((i) => i.code === code);
      lines.push(`## ${code} (${group.length})`);
      lines.push("");
      if (CODE_DOCS[code]) {
        lines.push(`> ${CODE_DOCS[code]}`);
        lines.push("");
      }
      lines.push("| severity | subject | detail | suggestion |");
      lines.push("| --- | --- | --- | --- |");
      for (const i of group) {
        lines.push(
          `| ${i.severity} | ${esc(i.subject)} | ${esc(i.detail)} | ${esc(i.suggestion ?? "")} |`,
        );
      }
      lines.push("");
    }

    if (this.issues.length === 0) {
      lines.push("No issues recorded.");
      lines.push("");
    }
    return lines.join("\n");
  }
}

function esc(s: string): string {
  return s.replace(/\|/g, "\\|").replace(/\n/g, " ");
}
